-- 3. Helpers
create or replace function loc_emirate(p bigint) returns text
language sql stable security definer set search_path = public as $$
  select coalesce(nullif(btrim(state_name), ''), city) from locations where id = p
$$;

create or replace function loc_label(p bigint) returns text
language sql stable security definer set search_path = public as $$
  select case when coalesce(state_name, '') in ('', city) then city else city || ', ' || state_name end
  from locations where id = p
$$;

-- great-circle distance in km; null when either side has no coordinates
create or replace function loc_distance_km(a bigint, b bigint) returns numeric
language sql stable security definer set search_path = public as $$
  select round((6371 * 2 * asin(sqrt(
           power(sin(radians(y.latitude - x.latitude) / 2), 2)
         + cos(radians(x.latitude)) * cos(radians(y.latitude)) * power(sin(radians(y.longitude - x.longitude) / 2), 2)
         )))::numeric, 1)
  from locations x, locations y
  where x.id = a and y.id = b and x.latitude is not null and y.latitude is not null
$$;

create or replace function couple_location(cid text) returns bigint
language sql stable security definer set search_path = public as $$
  select coalesce(pa.location_id, pb.location_id)
  from couples c
  left join people pa on pa.id = case when my_person() = c.partner_b then c.partner_b else c.partner_a end
  left join people pb on pb.id = case when my_person() = c.partner_b then c.partner_a else c.partner_b end
  where c.id = cid
$$;

create or replace function my_counsellor_id() returns uuid
language sql stable security definer set search_path = public as $$
  select id from counsellors where user_id = auth.uid()
$$;

-- is a location inside the signed-in admin's scope? (things with no location stay visible so they can be fixed)
create or replace function in_admin_scope(p bigint) returns boolean
language sql stable security definer set search_path = public as $$
  select coalesce((
    select case
      when a.role <> 'admin' then false
      when a.scope_level = 'national' or p is null then true
      when a.scope_level = 'emirate' then loc_emirate(p) is not distinct from loc_emirate(a.location_id)
      else p = a.location_id
    end
    from accounts a where a.user_id = auth.uid()), false)
$$;

create or replace function _audit(p_action text, p_type text, p_id text, p_meta jsonb default '{}'::jsonb) returns void
language sql security definer set search_path = public as $$
  insert into audit_log (actor, actor_name, action, resource_type, resource_id, metadata)
  select auth.uid(), coalesce((select display_name from accounts where user_id = auth.uid()), 'System'),
         p_action, p_type, p_id, p_meta
$$;
revoke all on function _audit(text, text, text, jsonb) from public, anon, authenticated;

-- admins may only verify / edit counsellors inside their scope
drop policy if exists counsellors_manage on counsellors;
create policy counsellors_manage on counsellors for update to authenticated
  using ((my_role() = 'admin' and in_admin_scope(location_id)) or user_id = auth.uid());

-- 4. Couple: where we live
create or replace function set_my_location(p_location bigint) returns text
language plpgsql security definer set search_path = public as $$
begin
  if my_person() is null then raise exception 'Only a couple member can set a home location'; end if;
  if p_location is not null and not exists (select 1 from locations where id = p_location) then
    raise exception 'Unknown location';
  end if;
  update people set location_id = p_location where id = my_person();
  return loc_label(p_location);
end $$;

-- 5. Counsellor clinic (the counsellor, or an admin whose scope covers both old and new location)
create or replace function set_counsellor_profile(
  p_counsellor uuid, p_location bigint, p_in_person boolean default true, p_online boolean default true
) returns void
language plpgsql security definer set search_path = public as $$
declare k counsellors;
begin
  select * into k from counsellors where id = coalesce(p_counsellor, my_counsellor_id()) for update;
  if not found then raise exception 'Counsellor not found'; end if;
  if k.user_id is distinct from auth.uid()
     and not (my_role() = 'admin' and in_admin_scope(k.location_id) and in_admin_scope(p_location)) then
    raise exception 'That counsellor is outside your area';
  end if;
  if not coalesce(p_in_person, false) and not coalesce(p_online, false) then
    raise exception 'Offer at least one: in person or online';
  end if;
  if p_in_person and p_location is null then
    raise exception 'Choose a clinic location to offer in-person sessions';
  end if;
  if p_location is not null and not exists (select 1 from locations where id = p_location) then
    raise exception 'Unknown location';
  end if;
  update counsellors
     set location_id = p_location, location = coalesce(loc_label(p_location), location),
         offers_in_person = p_in_person, offers_online = p_online
   where id = k.id;
  -- open, unrequested slots follow the counsellor to the new clinic
  update counsellor_availability set location_id = p_location
   where counsellor_id = k.id and not is_booked and not is_held and slot_start > now();
  perform _audit('Set counsellor clinic: ' || k.name || ' -> ' || coalesce(loc_label(p_location), 'none')
                 || case when p_in_person and p_online then ' (in person and online)'
                         when p_in_person then ' (in person only)' else ' (online only)' end,
                 'counsellors', k.id::text,
                 jsonb_build_object('from', k.location_id, 'to', p_location, 'in_person', p_in_person, 'online', p_online));
end $$;

-- 6. Admin scope (only a nationwide admin can change it)
create or replace function set_admin_scope(p_user uuid, p_level text, p_location bigint default null) returns void
language plpgsql security definer set search_path = public as $$
declare me accounts; target accounts;
begin
  select * into me from accounts where user_id = auth.uid();
  if me.role is distinct from 'admin' or me.scope_level <> 'national' then
    raise exception 'Only a nationwide DoH admin can change admin areas';
  end if;
  if p_level not in ('national', 'emirate', 'location') then raise exception 'Choose national, emirate or location'; end if;
  if p_level <> 'national' and p_location is null then raise exception 'Choose a location for this scope'; end if;
  select * into target from accounts where user_id = p_user for update;
  if not found or target.role <> 'admin' then raise exception 'That account is not a DoH admin'; end if;
  if p_user = auth.uid() and p_level <> 'national'
     and not exists (select 1 from accounts where role = 'admin' and scope_level = 'national' and user_id <> auth.uid()) then
    raise exception 'You are the only nationwide admin; keep your own scope national';
  end if;
  update accounts set scope_level = p_level, location_id = case when p_level = 'national' then location_id else p_location end
   where user_id = p_user;
  perform _audit('Set admin area: ' || target.display_name || ' -> '
                 || case p_level when 'national' then 'whole country'
                                 when 'emirate' then coalesce(loc_emirate(p_location), '?') || ' (emirate)'
                                 else coalesce(loc_label(p_location), '?') end,
                 'accounts', p_user::text, jsonb_build_object('level', p_level, 'location', p_location));
end $$;

-- 7. Counsellor publishes real, bookable slots (Gulf time)
create or replace function publish_slots(
  p_from date, p_to date, p_weekdays int[], p_start time, p_end time,
  p_minutes int default 45, p_gap int default 15, p_modality text default 'both'
) returns int
language plpgsql security definer set search_path = public as $$
declare k counsellors; n int;
begin
  select * into k from counsellors where user_id = auth.uid();
  if not found then raise exception 'Only a counsellor can publish slots'; end if;
  if p_modality not in ('online', 'in_person', 'both') then raise exception 'Choose online, in person or both'; end if;
  if p_modality <> 'online' and (k.location_id is null or not k.offers_in_person) then
    raise exception 'Set your clinic location (and turn on in-person) before publishing in-person slots';
  end if;
  if p_modality <> 'in_person' and not k.offers_online then
    raise exception 'Turn on online sessions before publishing online slots';
  end if;
  if p_from is null or p_to is null or p_to < p_from then raise exception 'Choose a valid date range'; end if;
  if p_from < (now() at time zone 'Asia/Dubai')::date then raise exception 'Start date is in the past'; end if;
  if p_to - p_from > 62 then raise exception 'Publish at most 9 weeks at a time'; end if;
  if p_start is null or p_end is null or p_end <= p_start then raise exception 'End time must be after start time'; end if;
  if p_minutes not between 15 and 120 or coalesce(p_gap, 0) not between 0 and 60 then raise exception 'Invalid session length or gap'; end if;
  if coalesce(array_length(p_weekdays, 1), 0) = 0 then raise exception 'Choose at least one working day'; end if;

  insert into counsellor_availability (counsellor_id, slot_start, slot_end, modality, location_id)
  select k.id, s.ts at time zone 'Asia/Dubai', (s.ts + make_interval(mins => p_minutes)) at time zone 'Asia/Dubai',
         p_modality, case when p_modality = 'online' then null else k.location_id end
  from generate_series(p_from::timestamp, p_to::timestamp, interval '1 day') as g(d)
  cross join lateral generate_series(g.d + p_start, g.d + p_end - make_interval(mins => p_minutes),
                                     make_interval(mins => p_minutes + coalesce(p_gap, 0))) as s(ts)
  where extract(isodow from g.d)::int = any (p_weekdays)
    and s.ts at time zone 'Asia/Dubai' > now()
  on conflict (counsellor_id, slot_start) do nothing;
  get diagnostics n = row_count;
  perform _audit('Published ' || n || ' slots ' || p_from || ' to ' || p_to || ' (' || replace(p_modality, '_', ' ') || ')',
                 'counsellor_availability', k.id::text, jsonb_build_object('count', n));
  return n;
end $$;

create or replace function remove_slot(p_slot uuid) returns void
language plpgsql security definer set search_path = public as $$
declare s counsellor_availability;
begin
  select * into s from counsellor_availability where id = p_slot for update;
  if not found or s.counsellor_id is distinct from my_counsellor_id() then raise exception 'Not your slot'; end if;
  if s.is_booked or s.is_held then raise exception 'A couple has requested or booked this time; decline or cancel it instead'; end if;
  delete from counsellor_availability where id = p_slot;
end $$;

-- 8. Couple: free slots ranked by my counsellor, then nearest
create or replace function find_slots(p_modality text default 'online', p_emirate text default null, p_limit int default 60)
returns table (
  slot_id uuid, slot_start timestamptz, slot_end timestamptz, modality text,
  counsellor_id uuid, counsellor_name text, gender text, languages text[],
  location_id bigint, location_label text, emirate text, distance_km numeric,
  is_my_counsellor boolean, match text
)
language plpgsql stable security definer set search_path = public as $$
#variable_conflict use_column
declare cid text := my_couple(); home bigint; mine uuid; tier int; area text;
begin
  if cid is null then raise exception 'Only a couple member can look for slots'; end if;
  if p_modality not in ('online', 'offline') then raise exception 'Choose online or offline'; end if;
  home := couple_location(cid);
  select cc.triage_tier, ca.counsellor_id into tier, mine
  from clinical_cases cc left join case_assignments ca on ca.case_id = cc.id and ca.status = 'active'
  where cc.couple_id = cid limit 1;
  area := coalesce(nullif(btrim(p_emirate), ''), loc_emirate(home));

  return query
  select * from (
    select s.id as slot_id, s.slot_start, s.slot_end, s.modality, k.id as counsellor_id, k.name as counsellor_name, k.gender, k.languages,
           coalesce(s.location_id, k.location_id) as location_id,
           loc_label(coalesce(s.location_id, k.location_id)) as location_label,
           loc_emirate(coalesce(s.location_id, k.location_id)) as emirate,
           loc_distance_km(home, coalesce(s.location_id, k.location_id)) as distance_km,
           k.id is not distinct from mine as is_my_counsellor,
           case when k.id is not distinct from mine then 'your_counsellor'
                when home is not null and coalesce(s.location_id, k.location_id) = home then 'same_location'
                when home is not null and loc_emirate(coalesce(s.location_id, k.location_id)) = loc_emirate(home) then 'same_emirate'
                else 'other' end as match
    from counsellor_availability s
    join counsellors k on k.id = s.counsellor_id
    where not s.is_booked and not coalesce(s.is_held, false) and s.slot_start > now()
      and k.status = 'active' and k.credentials_verified
      and (not s.is_emergency_buffer or tier = 1)
      and case when p_modality = 'online'
               then s.modality in ('online', 'both') and k.offers_online
               else s.modality in ('in_person', 'both') and k.offers_in_person
                    and coalesce(s.location_id, k.location_id) is not null
                    and (area is null or loc_emirate(coalesce(s.location_id, k.location_id)) = area)
          end
  ) r
  order by (r.match = 'your_counsellor') desc,
           array_position(array['same_location', 'same_emirate', 'other'], r.match),
           r.distance_km nulls last, r.slot_start
  limit greatest(1, least(coalesce(p_limit, 60), 200));
end $$;

-- 9. Request: validate the format against the slot and remember the clinic
create or replace function request_consultation(
  p_slot uuid,
  p_modality text default 'online',
  p_topic text default 'Pre-marital genetic counselling',
  p_notes text default null
) returns uuid
language plpgsql security definer set search_path = public as $$
declare
  cid text := my_couple();
  me text := my_person();
  s counsellor_availability;
  k counsellors;
  req_id uuid;
  mode text := coalesce(p_modality, 'online');
begin
  if cid is null then raise exception 'Only an authenticated couple member can request a consultation'; end if;
  if mode not in ('online', 'offline') then raise exception 'Choose online or in person'; end if;

  if exists (select 1 from consultation_requests where couple_id = cid and status = 'PENDING') then
    raise exception 'You already have a consultation request awaiting confirmation.';
  end if;
  if exists (select 1 from appointments where couple_id = cid and status = 'booked') then
    raise exception 'You already have an active booked consultation. Cancel it first to choose another time.';
  end if;

  select * into s from counsellor_availability where id = p_slot for update;
  if not found or s.is_booked or s.is_held or s.slot_start < now() then
    raise exception 'The selected slot is no longer available';
  end if;
  select * into k from counsellors where id = s.counsellor_id;
  if k.status <> 'active' or not k.credentials_verified then
    raise exception 'This counsellor is not taking bookings right now';
  end if;
  if mode = 'offline' and (s.modality = 'online' or not k.offers_in_person or coalesce(s.location_id, k.location_id) is null) then
    raise exception 'This time is online only. Choose an in-person time or switch to online.';
  end if;
  if mode = 'online' and (s.modality = 'in_person' or not k.offers_online) then
    raise exception 'This time is in person only. Choose an online time or switch to in person.';
  end if;

  req_id := gen_random_uuid();

  insert into consultation_requests (
    id, couple_id, requester_id, counsellor_id, slot_id,
    requested_starts_at, requested_ends_at, modality, topic,
    status, patient_notes, meet_link, location_id
  ) values (
    req_id, cid, me, s.counsellor_id, p_slot,
    s.slot_start, s.slot_end, mode, coalesce(p_topic, 'Pre-marital genetic counselling'),
    'PENDING', p_notes,
    case when mode = 'offline' then null else 'https://meet.google.com/dan-' || cid || '-' || substr(md5(random()::text), 1, 4) end,
    case when mode = 'offline' then coalesce(s.location_id, k.location_id) end
  );

  -- the request must exist before the slot can point at it (021 did this the other way round and always failed)
  update counsellor_availability set is_held = true, held_for_request_id = req_id where id = p_slot;

  return req_id;
end $$;

-- 10. Confirm: the appointment keeps the clinic location (otherwise unchanged from 021)
create or replace function confirm_consultation_request(p_request_id uuid) returns bigint
language plpgsql security definer set search_path = public as $$
declare
  req consultation_requests;
  c clinical_cases;
  appt_id bigint;
  k counsellors;
begin
  if my_role() <> 'counsellor' then
    raise exception 'Only a licensed counsellor can confirm appointments.';
  end if;

  select * into k from counsellors where user_id = auth.uid();

  select * into req from consultation_requests where id = p_request_id for update;
  if not found then raise exception 'Consultation request not found'; end if;
  if req.status <> 'PENDING' then raise exception 'Request has already been processed (status: %)', req.status; end if;

  select * into c from clinical_cases where couple_id = req.couple_id;

  insert into appointments (
    couple_id, starts_at, status, case_id, counsellor_id,
    slot_id, meeting_type, request_id, confirmed_at, confirmed_by, meet_link, location_id
  ) values (
    req.couple_id, req.requested_starts_at, 'booked', c.id, coalesce(req.counsellor_id, k.id),
    req.slot_id, req.modality, p_request_id, now(), k.id, req.meet_link, req.location_id
  ) returning id into appt_id;

  update consultation_requests
  set status = 'CONFIRMED',
      appointment_id = appt_id,
      responded_at = now(),
      responded_by = auth.uid(),
      counsellor_id = coalesce(req.counsellor_id, k.id)
  where id = p_request_id;

  if req.slot_id is not null then
    update counsellor_availability
    set is_booked = true, is_held = false, held_for_request_id = null
    where id = req.slot_id;
  end if;

  return appt_id;
end $$;

-- 11. New cases go to a counsellor in the couple's emirate first, then by free capacity
create or replace function upsert_case(cid text) returns uuid
language plpgsql security definer set search_path = public as $$
declare t int := compute_tier(cid); w int; v_case uuid; home bigint;
begin
  select pregnant_weeks into w from couples where id = cid;
  select coalesce(pa.location_id, pb.location_id) into home
  from couples c left join people pa on pa.id = c.partner_a left join people pb on pb.id = c.partner_b
  where c.id = cid;
  insert into clinical_cases (couple_id, clinical_urgency, is_pregnant, gestational_weeks, triage_tier)
  values (cid, (array['urgent', 'high', 'moderate', 'routine'])[t], w is not null, w, t)
  on conflict (couple_id) do update
    set triage_tier = excluded.triage_tier, clinical_urgency = excluded.clinical_urgency,
        is_pregnant = excluded.is_pregnant, gestational_weeks = excluded.gestational_weeks, updated_at = now()
  returning id into v_case;
  insert into case_assignments (case_id, counsellor_id, assignment_reason)
  select v_case, k.id,
         case when home is not null and loc_emirate(k.location_id) = loc_emirate(home)
              then 'auto: same emirate and caseload' else 'auto: caseload' end
  from counsellors k
  where k.status = 'active'
    and not exists (select 1 from case_assignments a where a.case_id = v_case and a.status = 'active')
  order by (home is not null and loc_emirate(k.location_id) = loc_emirate(home)) desc,
           (k.max_caseload - k.active_caseload) desc
  limit 1;
  return v_case;
end $$;
revoke execute on function upsert_case(text) from public;

-- 12. Admin views, limited to the admin's scope
create or replace function admin_counsellors() returns table (
  id uuid, name text, gender text, languages text[], status text, credentials_verified boolean,
  location_id bigint, location_label text, emirate text, offers_in_person boolean, offers_online boolean,
  active_caseload int, max_caseload int, open_slots_14d int, next_open_slot timestamptz
)
language plpgsql stable security definer set search_path = public as $$
#variable_conflict use_column
begin
  if my_role() is distinct from 'admin' then raise exception 'Only a DoH admin can view counsellors'; end if;
  return query
  select k.id, k.name, k.gender, k.languages, k.status, k.credentials_verified,
         k.location_id, loc_label(k.location_id), loc_emirate(k.location_id), k.offers_in_person, k.offers_online,
         (select count(*)::int from case_assignments a where a.counsellor_id = k.id and a.status = 'active'),
         k.max_caseload,
         (select count(*)::int from counsellor_availability s where s.counsellor_id = k.id and not s.is_booked
            and not coalesce(s.is_held, false) and s.slot_start between now() and now() + interval '14 days'),
         (select min(s.slot_start) from counsellor_availability s where s.counsellor_id = k.id and not s.is_booked
            and not coalesce(s.is_held, false) and s.slot_start > now())
  from counsellors k
  where in_admin_scope(k.location_id)
  order by k.credentials_verified desc, k.status, k.name;
end $$;

-- demand vs capacity per emirate; couple counts under 5 are hidden
create or replace function admin_coverage() returns table (
  emirate text, counsellors_active int, open_slots_14d int, couples_count text
)
language plpgsql stable security definer set search_path = public as $$
#variable_conflict use_column
declare me accounts;
begin
  select * into me from accounts where user_id = auth.uid();
  if me.role is distinct from 'admin' then raise exception 'Only a DoH admin can view coverage'; end if;
  return query
  with areas as (
    select loc_emirate(k.location_id) as em from counsellors k where k.location_id is not null
    union select loc_emirate(coalesce(pa.location_id, pb.location_id)) from couples c
      left join people pa on pa.id = c.partner_a left join people pb on pb.id = c.partner_b
  ), scoped as (
    select distinct a.em from areas a
    where a.em is not null
      and (me.scope_level = 'national' or a.em is not distinct from loc_emirate(me.location_id))
  )
  select s.em,
         (select count(*)::int from counsellors k where loc_emirate(k.location_id) = s.em and k.status = 'active' and k.credentials_verified),
         (select count(*)::int from counsellor_availability v join counsellors k on k.id = v.counsellor_id
            where loc_emirate(coalesce(v.location_id, k.location_id)) = s.em and not v.is_booked
              and not coalesce(v.is_held, false) and v.slot_start between now() and now() + interval '14 days'),
         (select case when count(*) < 5 then '<5' else count(*)::text end from couples c
            left join people pa on pa.id = c.partner_a left join people pb on pb.id = c.partner_b
            where loc_emirate(coalesce(pa.location_id, pb.location_id)) = s.em)
  from scoped s
  order by 1;
end $$;

