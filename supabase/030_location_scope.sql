-- =====================================================================
-- 030: Location scope for counsellors, admins, couples and bookings.
-- Run AFTER 021_consultation_requests.sql. Safe to re-run.
--
-- Uses public.locations (one row per city / neighbourhood, grouped by
-- state_name = emirate). Works with the live table (bigint id, double
-- coordinates) and with 029_locations.sql, in either order.
--
--   counsellors        clinic location + in-person / online offered
--   counsellor slots   modality (online / in_person / both) + location
--   accounts (admin)   scope: whole country, one emirate, or one location
--   people (couple)    where they live, used to suggest nearby counsellors
--   requests / appts   the clinic location of an in-person session
--
-- RPCs: set_my_location, set_counsellor_profile, set_admin_scope,
--       publish_slots, remove_slot, find_slots, admin_counsellors,
--       admin_coverage. request_consultation, confirm_consultation_request
--       and upsert_case are updated to use location.
-- =====================================================================

